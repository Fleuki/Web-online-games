/**
 * Настройки TreeGame.
 *
 * Всё, что стоит крутить при балансировке, собрано здесь: ядру эти числа
 * не видны, а клиент получает те из них, что нужны для отрисовки, через
 * состояние партии.
 */
export const treegameConfig = {
  /** Счёт, на котором партия заканчивается. */
  targetScore: 20,

  /** На сколько миллисекунд глушит удар со стороны ветки. */
  stunDurationMs: 1000,

  /** Размер порции, которой догенерируется ствол. */
  chunkSize: 50,

  /**
   * Первые сегменты гарантированно без веток: старт должен быть честным,
   * а не лотереей на первом же ударе.
   */
  safeStart: 5,

  /** Больше скольки веток подряд с одной стороны не бывает. */
  maxSameRun: 3,

  /** Доля сегментов с веткой. */
  branchChance: 0.6,

  /**
   * За сколько сегментов до конца сгенерированного участка догенерируется
   * следующая порция.
   */
  lookahead: 10,
} as const;

export type TreegameConfig = typeof treegameConfig;
